const bcrypt = require('bcryptjs');

function createTimestamp() {
  return new Date().toISOString();
}

function createSeedUser(id, displayName, email, username, phone, password, role) {
  const passwordHash = bcrypt.hashSync(password, 10);

  return {
    id,
    displayName,
    email,
    username,
    phone,
    password: passwordHash,
    passwordHash,
    role,
    isLocked: false,
    avatar: displayName.slice(0, 1).toUpperCase(),
  };
}

function createCustomerProfile(user, membershipPoints = 0, address = 'TP. Hồ Chí Minh') {
  return {
    id: user.id,
    userId: user.id,
    displayName: user.displayName,
    email: user.email,
    username: user.username,
    phone: user.phone,
    role: user.role,
    isLocked: Boolean(user.isLocked),
    avatar: user.avatar,
    membershipPoints,
    address,
    createdAt: createTimestamp(),
    updatedAt: createTimestamp(),
  };
}

function createEmployeeProfile(id, fullName, email, phone, position, gender, birthDate, address, avatar) {
  return {
    id,
    fullName,
    email,
    phone,
    position,
    gender,
    birthDate,
    address,
    avatar,
    status: 'active',
    createdAt: createTimestamp(),
    updatedAt: createTimestamp(),
  };
}

